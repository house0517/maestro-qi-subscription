def parse_solar_birth_datetime(raw):
    raw = str(raw or "").strip()
    if not raw:
        return None

    text = (
        raw.replace("年", "-")
        .replace("月", "-")
        .replace("日", " ")
        .replace("/", "-")
        .replace(".", "-")
        .replace("：", ":")
        .strip()
    )

    compact = re.match(
        r"^\s*(\d{4})(\d{2})(\d{2})(?:\s*(\d{1,2})(?::?(\d{2}))?)?\s*$",
        raw,
    )
    dashed = re.match(
        r"^\s*(\d{4})-(\d{1,2})-(\d{1,2})(?:\s+(\d{1,2})(?::(\d{1,2}))?)?\s*$",
        text,
    )
    match = compact or dashed
    if not match:
        return None

    year, month, day = [int(match.group(i)) for i in range(1, 4)]
    has_time = match.group(4) is not None
    hour = int(match.group(4)) if has_time else 12
    minute = int(match.group(5) or 0) if has_time else 0

    try:
        datetime.datetime(year, month, day, hour, minute)
    except ValueError:
        return None

    return {
        "year": year,
        "month": month,
        "day": day,
        "hour": hour,
        "minute": minute,
        "has_time": has_time,
    }


