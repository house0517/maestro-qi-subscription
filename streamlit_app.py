def save_to_sqlite(name, birth, report, history, ptype="single"):
    try:
        conn = sqlite3.connect(LOCAL_DB_PATH)
        c = conn.cursor()
        name, birth, ptype = normalize_record_identity(name, birth, ptype)
        history_str = history_to_text(history)
        date_now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

        c.execute(
            "SELECT id FROM records WHERE name=? AND birth_info=? AND ptype=?",
            (name, birth, ptype),
        )
        row = c.fetchone()

        if row:
            c.execute("UPDATE records SET report=?, history=?, date=?, ptype=? WHERE id=?",
                      (str(report), history_str, date_now, str(ptype), row[0]))
        else:
            c.execute("INSERT INTO records (name, birth_info, report, history, date, ptype) VALUES (?, ?, ?, ?, ?, ?)",
                      (str(name), str(birth), str(report), history_str, date_now, str(ptype)))

        conn.commit()
        conn.close()
        st.toast("⚡ 齐大师永久记忆已同步！")
        return True
    except Exception as e:
        st.error(f"数据库写入失败: {e}")
        return False


def save_to_gsheets(name, birth, report, history, ptype="single"):
    gsheets = get_gsheets_connection()
    if not gsheets:
        return False

    try:
        worksheet = get_gsheets_worksheet()
        df = normalize_records_df(gsheets.read(worksheet=worksheet, ttl=0))
        date_now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        name, birth, ptype = normalize_record_identity(name, birth, ptype)
        history_str = history_to_text(history)

        matched = (
            (df["name"].astype(str) == name)
            & (df["birth_info"].astype(str) == birth)
            & (df["ptype"].astype(str) == ptype)
        )
        if matched.any():
            idx = df.index[matched][0]
            if not int(df.loc[idx, "id"] or 0):
                df.loc[idx, "id"] = int(df["id"].max()) + 1 if not df.empty else 1
            df.loc[idx, ["name", "birth_info", "report", "history", "date", "ptype"]] = [
                name,
                birth,
                str(report),
                history_str,
                date_now,
                ptype,
            ]
        else:
            next_id = int(df["id"].max()) + 1 if not df.empty else 1
            df = pd.concat(
                [
                    df,
                    pd.DataFrame(
                        [
                            {
                                "id": next_id,
                                "name": name,
                                "birth_info": birth,
                                "report": str(report),
                                "history": history_str,
                                "date": date_now,
                                "ptype": ptype,
                            }
                        ],
                        columns=RECORD_COLUMNS,
                    ),
                ],
                ignore_index=True,
            )

        gsheets.update(worksheet=worksheet, data=df[RECORD_COLUMNS])
        read_gsheets_records.clear()
        st.toast("⚡ 齐大师云端档案已同步！")
        return True
    except Exception as e:
        st.error(f"Google Sheets 写入失败，已尝试保存到本地 SQLite：{e}")
        return False


def save_record(name, birth, report, history, ptype="single"):
    st.session_state.last_save_error = ""
    if not str(report or "").strip():
        st.session_state.last_save_error = "空报告不会写入档案库，请先重新生成正文。"
        st.error(st.session_state.last_save_error)
        return False
    identity_error = validate_record_identity(name, birth, ptype)
    if identity_error:
        st.error(identity_error)
        st.session_state.last_save_error = identity_error
        return False

    backend = active_storage_backend()
    cloud_saver = {"supabase": save_to_supabase, "gsheets": save_to_gsheets}.get(backend)
    if cloud_saver and cloud_saver(name, birth, report, history, ptype):
        st.session_state.last_save_ok = True
        return True

    saved_local = save_to_sqlite(name, birth, report, history, ptype)
    st.session_state.last_save_ok = saved_local
    if backend in ("supabase", "gsheets"):
        if saved_local:
            st.session_state.last_save_error = (
                f"云端 {STORAGE_SHORT_LABELS[backend]} 保存失败，已临时保存到本地 SQLite。"
                "线上环境重启后本地记录可能丢失，请稍后重试云端保存。"
            )
        else:
            st.session_state.last_save_error = "云端和本地保存都失败。本次结果已保留在当前页面，请先不要刷新页面。"
    return saved_local


def save_case_story_record(name, birth, report):
    """Save a public case without replacing the active personal report's save state."""
    previous_save_ok = st.session_state.get("last_save_ok", False)
    previous_save_error = st.session_state.get("last_save_error", "")
    saved = save_record(name, birth, report, [], "case_story")
    case_error = st.session_state.get("last_save_error", "")
    st.session_state.last_save_ok = previous_save_ok
    st.session_state.last_save_error = previous_save_error
    st.session_state.case_story_save_error = case_error
    return saved

