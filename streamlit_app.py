def require_workspace_access():
    """Protect API usage and consultation archives before rendering the workbench."""
    try:
        access_config = st.secrets.get("app_access", {})
        secret_password = access_config.get("password", "")
    except Exception:
        secret_password = ""
    access_password = os.environ.get("APP_ACCESS_PASSWORD", secret_password)
    if not access_password:
        st.error("请先在 Streamlit Secrets 的 [app_access] 中配置访问口令。")
        st.stop()
    password_fingerprint = hashlib.sha256(access_password.encode("utf-8")).hexdigest()
    if st.session_state.get("workspace_access_fingerprint") == password_fingerprint:
        return

    st.title("✦ Maestro Qi")
    st.subheader("会员咨询工作台")
    st.caption("请输入工作台访问口令。")
    with st.form("workspace_access_form"):
        entered_password = st.text_input("访问口令", type="password")
        submitted = st.form_submit_button("进入工作台", type="primary")
    if submitted:
        if hmac.compare_digest(entered_password, access_password):
            st.session_state.workspace_access_fingerprint = password_fingerprint
            st.rerun()
        st.error("口令不正确，请重试。")
    st.stop()


require_workspace_access()

